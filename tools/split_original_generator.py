def main(src):
    with open(src, encoding="utf-8") as f:
        lines = f.read().split("\n")
    digest = hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()

    def rng(a, b):  # 1-based inclusive
        return lines[a - 1:b]

    # sanity checks on the boundaries
    assert rng(201, 201)[0].startswith("PARAPHRASED_TASKS = {"), rng(201, 201)
    assert rng(218, 218)[0].strip() == "}", rng(218, 218)
    assert rng(471, 471)[0].strip() == "template = {", rng(471, 471)
    assert rng(864, 864)[0].strip() == "}", rng(864, 864)
    assert rng(872, 872)[0].strip().startswith("def search_frames_by_lu"), rng(872, 872)
    assert rng(5994, 5994)[0].strip() == "def main():", rng(5994, 5994)

    templates = [TEMPLATES_HEADER.replace("@@SHA@@", digest)]
    templates += rng(200, 218)
    templates += ["", "", "TEMPLATE = {"]
    templates += rng(472, 864)  # dict body, indentation inside braces is irrelevant
    with open(os.path.join(PKG, "templates.py"), "w", encoding="utf-8") as f:
        f.write("\n".join(templates).rstrip() + "\n")

    body = []
    for line in rng(865, 5991):
        stripped = line[8:] if line.startswith(" " * 8) else line.lstrip(" ")
        body.append(stripped.rstrip())
    builder = BUILDER_HEADER.replace("@@SHA@@", digest) + "\n".join(body).rstrip() + "\n" + BUILDER_FOOTER
    with open(os.path.join(PKG, "dataset_builder.py"), "w", encoding="utf-8") as f:
        f.write(builder)

    print("source sha256:", digest)
    print("wrote templates.py and dataset_builder.py")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
